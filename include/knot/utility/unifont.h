inline GLuint compile(GLenum type, const char* source) {
    GLuint shader = glCreateShader(type);
    glShaderSource(shader, 1, &source, nullptr);
    glCompileShader(shader);
    GLint ok = GL_FALSE;
    glGetShaderiv(shader, GL_COMPILE_STATUS, &ok);
    if (ok != GL_TRUE) {
        glDeleteShader(shader);
        return 0;
    }
    return shader;
}

struct State {
    GLuint program = 0, vao = 0, vbo = 0, texture = 0;
    bool ready = false;
};

inline State& state() {
    static State s;
    if (s.ready)
        return s;

    constexpr const char* vsSource = R"(#version 430 core
        layout(location=0) in vec2 position;
        layout(location=1) in vec2 uvIn;
        uniform vec2 viewportSize;
        out vec2 uv;
        void main() {
            uv = uvIn;
            gl_Position = vec4(2.0 * position.x / viewportSize.x - 1.0,
                               1.0 - 2.0 * position.y / viewportSize.y, 0.0, 1.0);
        }
    )";
    constexpr const char* fsSource = R"(#version 430 core
        in vec2 uv;
        uniform sampler2D fontTexture;
        uniform vec4 textColor;
        out vec4 color;
        void main() { color = vec4(textColor.rgb, textColor.a * texture(fontTexture, uv).r); }
    )";
    const GLuint vs = compile(GL_VERTEX_SHADER, vsSource);
    const GLuint fs = compile(GL_FRAGMENT_SHADER, fsSource);
    if (!vs || !fs) {
        if (vs)
            glDeleteShader(vs);
        if (fs)
            glDeleteShader(fs);
        return s;
    }
    s.program = glCreateProgram();
    glAttachShader(s.program, vs);
    glAttachShader(s.program, fs);
    glLinkProgram(s.program);
    glDeleteShader(vs);
    glDeleteShader(fs);
    GLint linked = GL_FALSE;
    glGetProgramiv(s.program, GL_LINK_STATUS, &linked);
    if (linked != GL_TRUE) {
        glDeleteProgram(s.program);
        s.program = 0;
        return s;
    }

    GLint previousActiveTexture = 0;
    glGetIntegerv(GL_ACTIVE_TEXTURE, &previousActiveTexture);
    glActiveTexture(GL_TEXTURE0);
    GLint previousTexture = 0;
    glGetIntegerv(GL_TEXTURE_BINDING_2D, &previousTexture);

    std::array<std::uint8_t, 80 * 160> pixels{};

    for (int glyph = 0; glyph < 100; ++glyph) {
        for (int row = 0; row < 16; ++row) {
            const std::uint8_t bits = glyphRows[glyph][row];
            for (int col = 0; col < 8; ++col)
                pixels[(glyph / 10 * 16 + row) * 80 + (glyph % 10 * 8 + col)] = (bits & (0x80u >> col)) ? 255 : 0;
        }
    }

    glGenTextures(1, &s.texture);
    glBindTexture(GL_TEXTURE_2D, s.texture);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, 80, 160, 0, GL_RED, GL_UNSIGNED_BYTE, pixels.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, static_cast<GLuint>(previousTexture));
    glActiveTexture(static_cast<GLenum>(previousActiveTexture));

    GLint previousVao = 0;
    GLint previousArrayBuffer = 0;
    glGetIntegerv(GL_VERTEX_ARRAY_BINDING, &previousVao);
    glGetIntegerv(GL_ARRAY_BUFFER_BINDING, &previousArrayBuffer);
    glGenVertexArrays(1, &s.vao);
    glGenBuffers(1, &s.vbo);
    glBindVertexArray(s.vao);
    glBindBuffer(GL_ARRAY_BUFFER, s.vbo);
    glBufferData(GL_ARRAY_BUFFER, 0, nullptr, GL_DYNAMIC_DRAW);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, sizeof(Vertex), nullptr);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, sizeof(Vertex), reinterpret_cast<void*>(2 * sizeof(float)));
    glBindVertexArray(static_cast<GLuint>(previousVao));
    glBindBuffer(GL_ARRAY_BUFFER, static_cast<GLuint>(previousArrayBuffer));
    s.ready = true;
    return s;
}

